"""Raw run JSON -> markdown: means with 95 % confidence intervals, per scenario.

Usage:  python bench/report.py bench/results/<session> [--out report.md]

Each run contributes ONE value per metric (its own mean over the run, or its
first-frame times averaged); the table shows the mean of those per-run values
across repetitions, ± the half-width of the 95 % Student interval, with n.
Two contenders whose intervals overlap show "no difference" - the report says
so rather than ranking them. No median is ever summarized (BENCHMARKS.md).

The markdown is generated, never hand-edited: re-run this script instead.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from stats import Interval, fmt, mean_ci  # noqa: E402

#: (key, label, unit, lower is better)
METRICS = [
    ("cpu_pct_core", "Server tree CPU", "% of one core", True),
    ("cpu_pct_machine", "Server tree CPU", "% of the machine", True),
    ("rss_mb", "Server tree RSS (mean)", "MiB", True),
    ("rss_mb_max", "Server tree RSS (max)", "MiB", True),
    ("private_mb", "Server tree private bytes", "MiB", True),
    ("first_frame_ms", "First frame (WHEP POST -> frame)", "ms", True),
    ("latency_ms_mean", "Glass-to-glass latency (mean)", "ms", True),
    ("latency_ms_p95", "Glass-to-glass latency (P95)", "ms", True),
    ("presented_fps", "Frames presented", "fps", False),
    ("frames_dropped", "Frames dropped (browser)", "frames", True),
    ("freezes", "Freezes (browser)", "count", True),
    ("reader_per_s", "RTSP reader packets", "per s", False),
    ("recovery_ms", "Recovery (source back -> frame)", "ms", True),
    ("background_cpu", "Machine CPU before the run", "%", None),
    ("machine_cpu", "Machine CPU during the run", "%", None),
]


def _mean(values):
    values = [v for v in values if v is not None]
    return sum(values) / len(values) if values else None


def run_metrics(record: dict) -> dict:
    """One value per metric for one run (None when the run has no such figure)."""
    summary = record.get("summary") or {}
    viewers = (record.get("browser") or {}).get("viewers") or []
    stats = [v.get("video_stats_last") or {} for v in viewers]
    first = [f for v in viewers for f in v.get("first_frame_ms") or []]
    readers = record.get("readers") or []
    recovery = [r for v in viewers for r in v.get("recovery_ms") or [] if r is not None]
    return {
        "cpu_pct_core": summary.get("cpu_pct_core_mean"),
        "cpu_pct_machine": summary.get("cpu_pct_machine_mean"),
        "rss_mb": summary.get("rss_mb_mean"),
        "rss_mb_max": summary.get("rss_mb_max"),
        "private_mb": summary.get("private_mb_mean"),
        "first_frame_ms": _mean(first),
        "latency_ms_mean": _mean([v.get("latency_ms_mean") for v in viewers]),
        "latency_ms_p95": _mean([v.get("latency_ms_p95") for v in viewers]),
        "presented_fps": _mean([v.get("presented_fps") for v in viewers]),
        "frames_dropped": _mean([s.get("framesDropped") for s in stats]),
        "freezes": _mean([s.get("freezeCount") for s in stats]),
        "reader_per_s": _mean([r.get("per_s") for r in readers]),
        "recovery_ms": _mean(recovery),
        "background_cpu": (record.get("background") or {}).get("machine_cpu_pct"),
        "machine_cpu": summary.get("machine_cpu_pct_mean"),
    }


def load(session: Path) -> list[dict]:
    runs = []
    for path in sorted(session.glob("*.json")):
        if path.name == "session.json":
            continue
        try:
            runs.append(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, ValueError) as err:
            print(f"skip {path.name}: {err}", file=sys.stderr)
    return runs


def verdict(intervals: dict[str, Interval | None], lower_is_better: bool | None) -> str:
    """Which contender is better on this row, or "no difference" when the CIs overlap."""
    present = {k: v for k, v in intervals.items() if v is not None}
    if lower_is_better is None or len(present) < 2:
        return ""
    ranked = sorted(present.items(), key=lambda kv: kv[1].mean, reverse=not lower_is_better)
    best, runner_up = ranked[0], ranked[1]
    if best[1].half_width is None or runner_up[1].half_width is None:
        return "n<2: no conclusion"
    if best[1].overlaps(runner_up[1]):
        return "no difference"
    return f"{best[0]} better"


def render(runs: list[dict], session: Path) -> str:
    lines = [f"# Bench report - {session.name}", "",
             "Generated by `bench/report.py` from the raw JSON; do not edit by hand.",
             "Values: mean of per-run values ± 95 % CI half-width (n runs). Overlapping CIs = no difference.", ""]
    meta = session / "session.json"
    if meta.is_file():
        skipped = json.loads(meta.read_text(encoding="utf-8")).get("skipped") or []
        if skipped:
            lines += ["## Skipped", ""]
            lines += [f"- {s.get('server') or s.get('scenario')}: {s['reason']}" for s in skipped]
            lines.append("")
    by_scenario: dict[str, list[dict]] = defaultdict(list)
    for run in runs:
        by_scenario[run["scenario"]["id"]].append(run)
    for sid in sorted(by_scenario):
        group = by_scenario[sid]
        title = group[0]["scenario"].get("title", "")
        lines += [f"## {sid} - {title}", ""]
        servers = sorted({(r.get("server") or {}).get("name") or r["run_id"].split("_")[1] for r in group})
        untested = sorted({(r.get("server") or {}).get("name") for r in group
                           if r.get("server") and not r["server"].get("tested_adapter")})
        if untested:
            lines += [f"> Untested adapter(s): {', '.join(untested)} - read servers/<name>.py before trusting.", ""]
        failed = [r for r in group if r.get("status") != "ok"]
        ok = [r for r in group if r.get("status") == "ok"]
        per_server: dict[str, list[dict]] = defaultdict(list)
        for r in ok:
            per_server[r["server"]["name"]].append(run_metrics(r))
        header = "| Metric | Unit | " + " | ".join(servers) + " | Verdict |"
        lines += [header, "|" + "---|" * (len(servers) + 3)]
        for key, label, unit, lower in METRICS:
            intervals = {s: mean_ci([m[key] for m in per_server.get(s, []) if m[key] is not None])
                         for s in servers}
            if all(v is None for v in intervals.values()):
                continue
            digits = 2 if unit.startswith("% of the") else 1
            cells = " | ".join(fmt(intervals[s], digits) for s in servers)
            lines.append(f"| {label} | {unit} | {cells} | {verdict(intervals, lower)} |")
        lines.append("")
        lines += ["Runs:", ""]
        for r in group:
            bg = (r.get("background") or {}).get("machine_cpu_pct")
            status = r.get("status")
            err = f" - {r.get('error')}" if status != "ok" else ""
            lines.append(f"- `{r['run_id']}` {status}, {r.get('duration_s')} s, machine CPU before: {bg} %{err}")
        if failed:
            lines += ["", f"{len(failed)} run(s) failed and are excluded from the table."]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("session", type=Path)
    parser.add_argument("--out", type=Path)
    ns = parser.parse_args(argv)
    text = render(load(ns.session), ns.session)
    if ns.out:
        ns.out.write_text(text, encoding="utf-8")
    sys.stdout.buffer.write(text.encode("utf-8") + b"\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
